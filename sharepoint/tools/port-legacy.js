/* ---------- CSS: scope every rule under the web part's root ---------- */
function scopeCss(css, root, renames = {}) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  for (const [a, b] of Object.entries(renames)) css = css.split(a).join(b);
  const out = [];
  let i = 0;
  const scopeSelector = (sel) => sel.split(',').map((s) => s.trim()).filter(Boolean).flatMap((s) => {
    if (s === 'html') return [];
    if (s === '*') return [root, `${root} *`];
    if (s.startsWith(':root')) return [root + s.slice(5)];
    if (s === 'body') return [root];
    if (/^body[.:[\s]/.test(s)) return [root + s.slice(4)];
    if (/^html[.:[\s]/.test(s)) return [`${root}${s.slice(4)}`];
    return [`${root} ${s}`];
  }).join(', ');
  function block(text, inKeyframes) {
    const res = [];
    let k = 0;
    while (k < text.length) {
      const open = text.indexOf('{', k);
      if (open < 0) break;
      const head = text.slice(k, open).trim();
      let depth = 1;
      let j = open + 1;
      while (j < text.length && depth) { if (text[j] === '{') depth++; else if (text[j] === '}') depth--; j++; }
      const inner = text.slice(open + 1, j - 1);
      if (head.startsWith('@media') || head.startsWith('@supports')) res.push(`${head} {\n${block(inner, false)}\n}`);
      else if (head.startsWith('@keyframes')) res.push(`${head} {${inner}}`);
      else if (inKeyframes) res.push(`${head} {${inner}}`);
      else {
        const sel = scopeSelector(head);
        if (sel) res.push(`${sel} {${inner}}`);
      }
      k = j;
    }
    return res.join('\n');
  }
  out.push(block(css, false));
  return out.join('\n');
}
