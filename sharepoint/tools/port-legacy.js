function rep(text, a, b, label) {
  if (!text.includes(a)) throw new Error(`[${label}] could not find: ${a.slice(0, 90)}`);
  return text.split(a).join(b);
}
function cut(text, from, to, label) {
  const i = text.indexOf(from);
  const j = text.indexOf(to, i + from.length);
  if (i < 0 || j < 0) throw new Error(`[${label}] could not cut ${from} … ${to}`);
  return text.slice(0, i) + text.slice(j);
}
const bodyOf = (html) => html.slice(html.indexOf('<body>') + 6, html.indexOf('</body>')).trim();

/* ---------- ids: prefix everything with sg- ---------- */
const boardHtmlRaw = bodyOf(read('public/index.html'));
const tvHtmlRaw = bodyOf(read('public/tv.html'));
const ids = [...new Set([...(boardHtmlRaw + tvHtmlRaw).matchAll(/\sid="([A-Za-z][\w-]*)"/g)].map((m) => m[1]))]
  .sort((a, b) => b.length - a.length);
const idRe = new RegExp(`#(${ids.join('|')})(?![\\w-])`, 'g');
function prefixIds(text) {
  return text
    .replace(/(\sid=")([A-Za-z][\w-]*)"/g, (m, a, id) => (ids.includes(id) ? `${a}sg-${id}"` : m))
    .replace(idRe, '#sg-$1')
    .replace(/getElementById\('([\w-]+)'\)/g, (m, id) => (ids.includes(id) ? `getElementById('sg-${id}')` : m));
}

/* ---------- a sandbox so global listeners/timers are removed on dispose ---------- */
const SANDBOX = `
  const disposers = [];
  const track = (target) => new Proxy(target, {
    get(t, p) {
      if (p === 'addEventListener') return (type, fn, opt) => { t.addEventListener(type, fn, opt); disposers.push(() => t.removeEventListener(type, fn, opt)); };
      const v = t[p];
      return typeof v === 'function' ? v.bind(t) : v;
    },
    set(t, p, v) { t[p] = v; return true; },
  });
  const window = track(globalThis.window);
  const document = track(globalThis.document);
  const setInterval = (fn, ms) => { const id = globalThis.setInterval(fn, ms); disposers.push(() => globalThis.clearInterval(id)); return id; };
  const timeouts = new Set();
  const setTimeout = (fn, ms) => { const id = globalThis.setTimeout(() => { timeouts.delete(id); fn(); }, ms); timeouts.add(id); return id; };
  const clearTimeout = (id) => { timeouts.delete(id); globalThis.clearTimeout(id); };
  disposers.push(() => { for (const id of timeouts) globalThis.clearTimeout(id); });
`;
const DISPOSE = `
  return { dispose() { while (disposers.length) { try { disposers.pop()(); } catch { /* ignore */ } } } };
`;

