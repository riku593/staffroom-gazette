/*
 * Ports the self-hosted Staffroom Gazette front end (../public, ../lib) into
 * SPFx modules under src/webparts/staffroomGazette/legacy/.
 *
 * Run from the sharepoint/ folder:  node tools/port-legacy.js
 *
 * What it does:
 *  - wraps the board and TV scripts in start functions that can be disposed
 *    (SharePoint pages navigate without full reloads)
 *  - swaps calls to the Node server for a "host" object backed by SharePoint
 *  - prefixes element ids (sg-…) and scopes all CSS under the web part root,
 *    so nothing clashes with the SharePoint page
 * Re-run it after changing the files in ../public to bring the changes across.
 */
